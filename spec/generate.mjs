#!/usr/bin/env node
// Generates the golden conformance fixtures in spec/.
// This is the single source of truth: every language port asserts against these
// numbers, which is how we know the four implementations agree to the bit.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

// The reference scale. Deliberately the same numbers as the original SCSS pen
// (400->800px viewport, 12->24px root) so the fixtures can be eyeballed.
const REF = {
  minWidth: 400,
  maxWidth: 800,
  minRootSize: 12,
  maxRootSize: 24,
  ratio: 1.2,
};

// Line-height anchors, shared by every port.
const LOOSE_AT = 16, TIGHT_AT = 48, LOOSE = 1.5, TIGHT = 1.1;

const clamp = (v, lo, hi) => (v < lo ? lo : v > hi ? hi : v);

function rootSize(s, width) {
  // The upper plateau is tested first on purpose: when minWidth == maxWidth
  // the scale degenerates to a single breakpoint, and this ordering makes it
  // step up to maxRootSize there instead of down. It also means the division
  // below can never see a zero denominator.
  if (width >= s.maxWidth) return s.maxRootSize;
  if (width <= s.minWidth) return s.minRootSize;
  const t = (width - s.minWidth) / (s.maxWidth - s.minWidth);
  return s.minRootSize + (s.maxRootSize - s.minRootSize) * t;
}

const sizeForStep = (s, step, width) => rootSize(s, width) * Math.pow(s.ratio, step);

function lineHeight(fontSize) {
  const t = clamp((fontSize - LOOSE_AT) / (TIGHT_AT - LOOSE_AT), 0, 1);
  return LOOSE + (TIGHT - LOOSE) * t;
}

const f = (n) => n.toFixed(10);

const WIDTHS = [0, 1, 320, 359.5, 400, 400.0001, 440, 500, 568, 600, 640, 700,
                768, 799.9999, 800, 834, 1024, 1280, 2560];
const STEPS = [-3, -2, -1, 0, 1, 2, 3, 4, 5, 6];
const STEP_WIDTHS = [320, 400, 500, 600, 700, 800, 1280];
const LH_SIZES = [8, 12, 15.9, 16, 20, 24, 31.1, 32, 40, 47.9, 48, 60, 96];

function table(header, rows) {
  return [
    `# fluid-type conformance fixture - generated by spec/generate.mjs, do not edit`,
    `# scale: minWidth=${REF.minWidth} maxWidth=${REF.maxWidth} ` +
      `minRootSize=${REF.minRootSize} maxRootSize=${REF.maxRootSize} ratio=${REF.ratio}`,
    header.join('\t'),
    ...rows.map((r) => r.join('\t')),
  ].join('\n') + '\n';
}

writeFileSync(
  join(here, 'root-size.tsv'),
  table(['width', 'rootSize'], WIDTHS.map((w) => [f(w), f(rootSize(REF, w))])),
);

writeFileSync(
  join(here, 'scale-steps.tsv'),
  table(['width', 'step', 'size'],
    STEP_WIDTHS.flatMap((w) => STEPS.map((s) => [f(w), String(s), f(sizeForStep(REF, s, w))]))),
);

writeFileSync(
  join(here, 'line-height.tsv'),
  table(['fontSize', 'lineHeight'], LH_SIZES.map((s) => [f(s), f(lineHeight(s))])),
);

console.log('wrote root-size.tsv, scale-steps.tsv, line-height.tsv');
